/**
 * Storefront chrome, rendered from the active theme's validated design
 * values and layout variants (ADR-031). Themes choose; the core renders.
 * Cart, checkout and account behaviour stay in the core.
 */
export default function StorefrontLayout({
    children,
}: {
    children: ReactNode;
}) {
    const { storefront } = usePage().props;
    const { header, footer, theme } = useStoreTheme();
    useFlashToast();

    return (
        <div className="storefront flex min-h-screen flex-col bg-background text-foreground">
            {theme && (
                <>
                    {/* Generated by the server from validated values only. */}
                    <style>{theme.css}</style>
                    {theme.favicon && (
                        <Head>
                            <link rel="icon" href={theme.favicon} />
                        </Head>
                    )}
                </>
            )}
            <a
                href="#main"
                className="sr-only focus:not-sr-only focus:absolute focus:top-2 focus:left-2 focus:z-50 focus:rounded focus:bg-background focus:px-3 focus:py-2"
            >
                Skip to content
            </a>
            {storefront?.themePreview && (
                <PreviewBanner preview={storefront.themePreview} />
            )}
            {theme?.announcement && (
                <div className="bg-primary px-4 py-2 text-center text-sm text-primary-foreground">
                    {theme.announcement}
                </div>
            )}
            {header === 'centered' ? (
                <CenteredHeader />
            ) : header === 'minimal' ? (
                <MinimalHeader />
            ) : (
                <ClassicHeader />
            )}
            <main
                id="main"
                className="mx-auto w-full max-w-[var(--store-container,72rem)] flex-1 px-4 py-8"
            >
                {children}
            </main>
            {footer === 'columns' ? <ColumnsFooter /> : <SimpleFooter />}
        </div>
    );
}

function Brand({ className }: { className?: string }) {
    const { storefront } = usePage().props;
    const name = storefront?.storeName ?? '';
    const logo = storefront?.theme.logo;

    return (
        <Link
            href={home()}
            className={cn('text-lg font-semibold', className)}
            aria-label={logo ? name : undefined}
        >
            {logo ? (
                <img src={logo} alt="" className="h-8 w-auto max-w-48" />
            ) : (
                name
            )}
        </Link>
    );
}

function SearchForm({ className }: { className?: string }) {
    return (
        <Form
            {...search.form()}
            className={cn('flex items-center gap-2', className)}
            role="search"
        >
            <Input
                type="search"
                name="q"
                placeholder="Search products"
                aria-label="Search products"
            />
            <Button
                type="submit"
                variant="outline"
                size="icon"
                aria-label="Search"
            >
                <Search />
            </Button>
        </Form>
    );
}

/** Shown when the store offers more than one language. */
function LanguageSwitcher() {
    const { storefront } = usePage().props;

    if (!storefront || storefront.locales.length < 2) {
        return null;
    }

    const change = (code: string) => {
        const params = new URLSearchParams(window.location.search);
        params.set('lang', code);
        router.visit(`${window.location.pathname}?${params.toString()}`, {
            preserveScroll: true,
        });
    };

    return (
        <label className="flex items-center gap-1 text-sm">
            <Globe className="size-4" aria-hidden />
            <span className="sr-only">Language</span>
            <select
                value={storefront.locale}
                onChange={(e) => change(e.target.value)}
                className="h-8 rounded-md border bg-transparent px-1 text-sm"
            >
                {storefront.locales.map((l) => (
                    <option key={l.code} value={l.code} lang={l.code}>
                        {l.name}
                    </option>
                ))}
            </select>
        </label>
    );
}

function AccountLinks() {
    const { storefront, auth } = usePage().props;
    const cartCount = storefront?.cartCount ?? 0;

    return (
        <nav className="flex items-center gap-1" aria-label="Account">
            <LanguageSwitcher />
            <Button variant="ghost" size="sm" asChild>
                <Link href={auth.user ? dashboard() : login()}>
                    <User />
                    <span className="hidden sm:inline">
                        {auth.user
                            ? auth.isStaff
                                ? 'Admin'
                                : 'Account'
                            : 'Log in'}
                    </span>
                </Link>
            </Button>
            <Button variant="outline" size="sm" asChild>
                <Link href={cartShow()} aria-label={`Cart, ${cartCount} items`}>
                    <ShoppingBag />
                    <span className="tabular-nums">{cartCount}</span>
                </Link>
            </Button>
        </nav>
    );
}

function CategoryNav({ centered = false }: { centered?: boolean }) {
    const { storefront } = usePage().props;

    if (!storefront || storefront.categories.length === 0) {
        return null;
    }

    return (
        <nav aria-label="Categories" className="border-t">
            <ul
                className={cn(
                    'mx-auto flex max-w-[var(--store-container,72rem)] gap-5 overflow-x-auto px-4 py-2 text-sm',
                    centered && 'justify-center',
                )}
            >
                <li>
                    <Link
                        href={search()}
                        className="whitespace-nowrap text-muted-foreground hover:text-foreground"
                    >
                        All products
                    </Link>
                </li>
                {storefront.categories.map((c) => (
                    <li key={c.id}>
                        <Link
                            href={category(c.slug)}
                            className="whitespace-nowrap text-muted-foreground hover:text-foreground"
                        >
                            {c.name}
                        </Link>
                    </li>
                ))}
            </ul>
        </nav>
    );
}

function ClassicHeader() {
    return (
        <header className="border-b">
            <div className="mx-auto flex max-w-[var(--store-container,72rem)] flex-wrap items-center gap-3 px-4 py-3">
                <Brand className="mr-auto" />
                <SearchForm className="order-last w-full sm:order-none sm:w-72" />
                <AccountLinks />
            </div>
            <CategoryNav />
        </header>
    );
}

function CenteredHeader() {
    return (
        <header className="border-b">
            <div className="mx-auto grid max-w-[var(--store-container,72rem)] grid-cols-[1fr_auto_1fr] items-center gap-3 px-4 py-4">
                <SearchForm className="hidden w-64 md:flex" />
                <Brand className="col-start-2 text-center text-xl tracking-wide" />
                <div className="col-start-3 flex justify-end">
                    <AccountLinks />
                </div>
            </div>
            <CategoryNav centered />
        </header>
    );
}

